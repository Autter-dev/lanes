// Renders what each install channel needs for one release, from the release's SHA256SUMS:
//   dist/lanes.rb         the Homebrew formula (the tap copies it from the latest release)
//   dist/lanes.json       the Scoop manifest (the bucket copies it from the latest release)
//   dist/winget/...       the winget manifests, for a pull request to microsoft/winget-pkgs
//   <notes>               release notes, from CHANGELOG.md
//
//   node packaging/render.mjs --version 0.1.0 --dist dist --notes notes.md

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = 'Autter-dev/lanes';
const HOMEPAGE = 'https://lanes.autter.dev';
const DESCRIPTION = "Run many coding agents on one repo without them getting in each other's way";
const root = join(dirname(fileURLToPath(import.meta.url)), '..');

const args = {};
for (let i = 2; i < process.argv.length; i += 2) args[process.argv[i].replace(/^--/, '')] = process.argv[i + 1];
const version = (args.version ?? '').replace(/^v/, '');
const dist = args.dist ?? 'dist';
if (!/^\d+\.\d+\.\d+(-[0-9A-Za-z.-]+)?$/.test(version)) {
  console.error('render: pass the release version, like --version 0.1.0');
  process.exit(2);
}

const base = `https://github.com/${REPO}/releases/download/v${version}`;
const sums = {};
for (const line of readFileSync(join(dist, 'SHA256SUMS'), 'utf8').split('\n')) {
  const m = line.match(/^([0-9a-f]{64})\s+\*?(.+)$/);
  if (m) sums[m[2].trim()] = m[1];
}

function asset(target) {
  const ext = target.includes('windows') ? 'zip' : 'tar.gz';
  const name = `lanes-${version}-${target}.${ext}`;
  if (!sums[name]) throw new Error(`render: ${name} isn't in ${dist}/SHA256SUMS. Build every target first.`);
  return { name, url: `${base}/${name}`, sha: sums[name], dir: `lanes-${version}-${target}` };
}

const mac = { arm: asset('aarch64-apple-darwin'), intel: asset('x86_64-apple-darwin') };
const linux = { arm: asset('aarch64-unknown-linux-musl'), intel: asset('x86_64-unknown-linux-musl') };
const win = { x64: asset('x86_64-pc-windows-msvc'), arm64: asset('aarch64-pc-windows-msvc') };

// ---------- Homebrew ----------

const brewBlock = (a) => `      url "${a.url}"\n      sha256 "${a.sha}"`;
writeFileSync(
  join(dist, 'lanes.rb'),
  `# Generated by packaging/render.mjs for Lanes ${version}. Don't edit by hand.
class Lanes < Formula
  desc "${DESCRIPTION}"
  homepage "${HOMEPAGE}"
  version "${version}"
  license "AGPL-3.0-only"

  on_macos do
    on_arm do
${brewBlock(mac.arm)}
    end
    on_intel do
${brewBlock(mac.intel)}
    end
  end

  on_linux do
    on_arm do
${brewBlock(linux.arm)}
    end
    on_intel do
${brewBlock(linux.intel)}
    end
  end

  def install
    bin.install "lane", "laned"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/lane --version")
  end
end
`,
);

// ---------- Scoop ----------

const scoopArch = (a, target) => ({ url: a.url, hash: a.sha, extract_dir: a.dir, _target: target });
const scoop = {
  version,
  description: DESCRIPTION,
  homepage: HOMEPAGE,
  license: 'AGPL-3.0-only',
  architecture: {
    '64bit': scoopArch(win.x64, 'x86_64-pc-windows-msvc'),
    arm64: scoopArch(win.arm64, 'aarch64-pc-windows-msvc'),
  },
  bin: ['lane.exe', 'laned.exe'],
  checkver: { github: `https://github.com/${REPO}` },
  autoupdate: { architecture: {}, hash: { url: '$url.sha256' } },
};
for (const [key, a] of Object.entries(scoop.architecture)) {
  scoop.autoupdate.architecture[key] = {
    url: `https://github.com/${REPO}/releases/download/v$version/lanes-$version-${a._target}.zip`,
    extract_dir: `lanes-$version-${a._target}`,
  };
  delete a._target;
}
writeFileSync(join(dist, 'lanes.json'), JSON.stringify(scoop, null, 2) + '\n');

// ---------- winget ----------

const wingetDir = join(dist, 'winget', 'manifests', 'a', 'Autter', 'Lanes', version);
mkdirSync(wingetDir, { recursive: true });
const header = (type) => `# yaml-language-server: $schema=https://aka.ms/winget-manifest.${type}.1.12.0.schema.json\n# Generated by packaging/render.mjs for Lanes ${version}.\n`;
const wingetInstaller = (arch, a) => `  - Architecture: ${arch}
    InstallerUrl: ${a.url}
    InstallerSha256: ${a.sha.toUpperCase()}
    NestedInstallerFiles:
      - RelativeFilePath: ${a.dir}\\lane.exe
        PortableCommandAlias: lane
      - RelativeFilePath: ${a.dir}\\laned.exe
        PortableCommandAlias: laned`;
writeFileSync(
  join(wingetDir, 'Autter.Lanes.yaml'),
  `${header('version')}
PackageIdentifier: Autter.Lanes
PackageVersion: ${version}
DefaultLocale: en-US
ManifestType: version
ManifestVersion: 1.12.0
`,
);
writeFileSync(
  join(wingetDir, 'Autter.Lanes.installer.yaml'),
  `${header('installer')}
PackageIdentifier: Autter.Lanes
PackageVersion: ${version}
InstallerType: zip
NestedInstallerType: portable
Commands:
  - lane
  - laned
Installers:
${wingetInstaller('x64', win.x64)}
${wingetInstaller('arm64', win.arm64)}
ManifestType: installer
ManifestVersion: 1.12.0
`,
);
writeFileSync(
  join(wingetDir, 'Autter.Lanes.locale.en-US.yaml'),
  `${header('defaultLocale')}
PackageIdentifier: Autter.Lanes
PackageVersion: ${version}
PackageLocale: en-US
Publisher: Autter
PublisherUrl: https://autter.dev
PublisherSupportUrl: https://github.com/${REPO}/issues
PackageName: Lanes
PackageUrl: ${HOMEPAGE}
License: AGPL-3.0-only
LicenseUrl: https://github.com/${REPO}/blob/main/LICENSE
ShortDescription: ${DESCRIPTION}
Moniker: lanes
Tags:
  - ai-agents
  - coding-agents
  - git
  - worktree
  - cli
ReleaseNotesUrl: https://github.com/${REPO}/releases/tag/v${version}
ManifestType: defaultLocale
ManifestVersion: 1.12.0
`,
);

// ---------- release notes ----------

if (args.notes) {
  const changelog = readFileSync(join(root, 'CHANGELOG.md'), 'utf8');
  // The section for this version if it has one, otherwise everything under "Unreleased".
  const section = (heading) => {
    const lines = changelog.split('\n');
    const start = lines.findIndex((l) => heading.test(l));
    if (start < 0) return '';
    const end = lines.findIndex((l, i) => i > start && /^## /.test(l));
    return lines.slice(start + 1, end < 0 ? undefined : end).join('\n').trim();
  };
  const escaped = version.replace(/\./g, '\\.');
  const changes = section(new RegExp(`^## \\[?v?${escaped}\\]?`)) || section(/^## Unreleased/);
  const notes = `Install or update:

| On | Command |
| --- | --- |
| macOS, Linux, WSL | \`brew install autter-dev/tap/lanes\`, or \`curl -fsSL https://github.com/${REPO}/releases/latest/download/lanes-installer.sh \\| sh\` |
| Windows | \`winget install Autter.Lanes\`, \`scoop install lanes\` (after \`scoop bucket add autter https://github.com/Autter-dev/scoop-bucket\`), or \`irm https://github.com/${REPO}/releases/latest/download/lanes-installer.ps1 \\| iex\` |
| Anywhere with Node | \`npm install -g @autter/lanes\` |

More ways, and how to check a download, at ${HOMEPAGE}/download.

Verify an archive: \`gh attestation verify <file> --repo ${REPO}\`, or compare it with \`SHA256SUMS\`.

## Changes

${changes || 'See CHANGELOG.md.'}
`;
  writeFileSync(args.notes, notes);
}

console.log(`render: Homebrew, Scoop and winget files for Lanes ${version} are in ${dist}.`);
